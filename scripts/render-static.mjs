import { readFile, writeFile } from 'node:fs/promises';
import { SitePage, routes } from '../components.js';

const template = await readFile(new URL('./page-template.html', import.meta.url), 'utf8');
const outputPaths = new Map([
  ['/', 'index.html'],
  ['/nextrain', 'nextrain/index.html'],
  ['/nether-portal', 'nether-portal/index.html'],
  ['/metropolis', 'metropolis/index.html'],
]);

if (routes.length !== outputPaths.size || routes.some(route => !outputPaths.has(route))) {
  throw new Error('Static entry points must match the routes in design-data.js');
}

function localizeMarkup(markup, base) {
  return markup
    .replace(/(src|href)="\/assets\//g, (_, attribute) => `${attribute}="${base}assets/`)
    .replace(/href="(\/[^"]*)"/g, (original, path) => {
      const route = path.replace(/\/+$/, '') || '/';
      return outputPaths.has(route) ? `href="${base}${outputPaths.get(route)}"` : original;
    });
}

for (const [route, outputPath] of [...outputPaths, ['/', '404.html']]) {
  const page = SitePage(route);
  const base = outputPath.includes('/') ? '../' : './';
  const html = template
    .replace('__PAGE_TITLE__', page.title)
    .replace('__STATIC_PATH__', route)
    .replace('__I18N_PAGE__', outputPath === '404.html' ? '404' : outputPath === 'index.html' ? 'index' : outputPath.split('/')[0])
    .replaceAll('__BASE__', base)
    .replace('__PAGE_HTML__', localizeMarkup(page.html, base));
  await writeFile(new URL(`../${outputPath}`, import.meta.url), html);
  console.log(`Rendered ${outputPath}`);
}

const carouselSource = await readFile(new URL('../carousel.js', import.meta.url), 'utf8');
const localRuntime = await readFile(new URL('./local-runtime.js', import.meta.url), 'utf8');
const standaloneCarousel = carouselSource.replace('export function bindHomeCarousel', 'function bindHomeCarousel');
if (standaloneCarousel === carouselSource) throw new Error('Could not bundle the local carousel');
await writeFile(new URL('../local.js', import.meta.url),
  `// Generated by node scripts/render-static.mjs.\n${standaloneCarousel}\n${localRuntime}`);
console.log('Rendered local.js');

// Classic scripts can load beside file:// pages, while fetch of local JSON is blocked
// by most browsers. Keep this generated fallback in sync with the JSON sources.
const languageScopes = ['common', 'index', 'nextrain', 'nether-portal', 'metropolis', '404', 'mcmods'];
const languageCatalog = {};
for (const scope of languageScopes) {
  languageCatalog[scope] = {};
  for (const language of ['zh_CN', 'en']) {
    const source = await readFile(new URL(`../lang/${scope}/${language}.json`, import.meta.url), 'utf8');
    languageCatalog[scope][language] = JSON.parse(source);
  }
  const chineseKeys = Object.keys(languageCatalog[scope].zh_CN).sort();
  const englishKeys = Object.keys(languageCatalog[scope].en).sort();
  if (JSON.stringify(chineseKeys) !== JSON.stringify(englishKeys)) {
    throw new Error(`Mismatched localization keys in lang/${scope}`);
  }
}
await writeFile(new URL('../lang/offline-bundle.js', import.meta.url),
  `// Generated from lang/*/*.json by node scripts/render-static.mjs.\nwindow.dovecotOfflineLanguages = ${JSON.stringify(languageCatalog).replace(/[\u2028\u2029]/g, character => character === '\u2028' ? '\\u2028' : '\\u2029')};\n`);
console.log('Rendered lang/offline-bundle.js');
